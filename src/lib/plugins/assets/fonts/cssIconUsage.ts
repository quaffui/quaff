import postcss, { CssSyntaxError, type AnyNode, type Root, type Rule } from "postcss";
import { addSymbolNames } from "./iconSymbolNames.js";
import type { IconSourceUsage } from "./iconSourceUsage.js";

export const ICON_FONT_PATTERN = /Material Symbols|var\(\s*--font-icon\s*\)/;
const CSS_CLASS_PATTERN = /\.(-?[_a-zA-Z]+[_a-zA-Z0-9-]*)/g;
const CSS_STRING_PATTERN = /"((?:\\.|[^"\\])*)"|'((?:\\.|[^'\\])*)'/g;

type CssIconValues = { names: Set<string>; complete: boolean };

type CssIconScan = ReturnType<typeof createCssIconScan>;

/** CSS content is an icon only when its rule uses, or shares a class with, an icon font. */
export function collectCssIconUsage(css: string, usage: IconSourceUsage, isPreprocessed = false) {
  const root = parseIconStylesheet(css, usage, isPreprocessed);

  if (!root) {
    return new Set<string>();
  }

  const scan = createCssIconScan();
  collectFontDeclarations(root, scan);
  collectIconContent(root, scan, usage);

  return scan.textClasses;
}

function parseIconStylesheet(css: string, usage: IconSourceUsage, isPreprocessed: boolean) {
  try {
    return postcss.parse(css);
  } catch (error) {
    if (!isPreprocessed || !(error instanceof CssSyntaxError)) {
      throw error;
    }

    usage.unresolved.push({
      expression: error.reason,
      reason: "Safelist icons generated by unsupported stylesheet preprocessor syntax.",
      line: error.line,
    });
  }
}

function createCssIconScan() {
  return {
    iconClasses: new Set([
      "q-icon",
      "material-symbols-outlined",
      "material-symbols-rounded",
      "material-symbols-sharp",
    ]),
    textClasses: new Set<string>(),
    variables: new Map<string, Set<string>>(),
  };
}

function collectFontDeclarations(root: Root, scan: CssIconScan) {
  root.walkDecls((declaration) => {
    if (declaration.prop.startsWith("--")) {
      scan.variables.set(
        declaration.prop,
        new Set([...(scan.variables.get(declaration.prop) ?? []), declaration.value])
      );
    }

    if (
      !["font", "font-family"].includes(declaration.prop) ||
      !ICON_FONT_PATTERN.test(declaration.value)
    ) {
      return;
    }

    const rule = declaration.parent;

    if (rule?.type !== "rule") {
      return;
    }

    collectFontClasses(rule, scan);
  });
}

function collectFontClasses(rule: Rule, scan: CssIconScan) {
  for (const match of rule.selector.matchAll(CSS_CLASS_PATTERN)) {
    scan.iconClasses.add(match[1]);
  }

  for (const selector of rule.selector.split(",")) {
    const simple = selector.trim().match(/^\.([\w-]+)$/);

    if (simple) {
      scan.textClasses.add(simple[1]);
    }
  }
}

function collectIconContent(root: Root, scan: CssIconScan, usage: IconSourceUsage) {
  root.walkDecls("content", (declaration) => {
    const rule = declaration.parent;

    if (rule?.type !== "rule" || !doesRuleUseIconFont(rule, scan.iconClasses)) {
      return;
    }

    const values = readCssValues(declaration.value, scan.variables);
    values.names.forEach((name) => addSymbolNames(usage.names, name));

    if (!values.complete) {
      usage.unresolved.push({
        expression: declaration.toString(),
        reason: "Safelist icon names supplied by computed CSS content.",
        line: declaration.source?.start?.line,
      });
    }
  });
}

function doesRuleUseIconFont(rule: Rule, iconClasses: ReadonlySet<string>) {
  const family = rule.nodes.findLast(
    (node) => node.type === "decl" && ["font", "font-family"].includes(node.prop)
  );

  if (family?.type === "decl") {
    return ICON_FONT_PATTERN.test(family.value);
  }

  if (
    [...rule.selector.matchAll(CSS_CLASS_PATTERN)].some(
      (match) => iconClasses.has(match[1]) || match[1].startsWith("q-icon--")
    )
  ) {
    return true;
  }

  for (let ancestor: AnyNode | undefined = rule.parent; ancestor; ancestor = ancestor.parent) {
    if (ancestor.type === "rule") {
      return doesRuleUseIconFont(ancestor, iconClasses);
    }
  }

  return false;
}

function readCssValues(
  value: string,
  variables: ReadonlyMap<string, Set<string>>,
  depth = 0
): CssIconValues {
  if (depth > 12) {
    return { names: new Set(), complete: false };
  }

  const literals = [...value.matchAll(CSS_STRING_PATTERN)].map((match) =>
    decodeCssString(match[1] ?? match[2])
  );
  const expression = value.replace(CSS_STRING_PATTERN, "");
  const hasPrivateUnicode = literals.some((literal) => /[\uE000-\uF8FF]/.test(literal));
  const result: CssIconValues = {
    names: new Set(literals),
    complete:
      !/\b(?:attr|env)\(|\$[\w-]+/.test(expression) && !value.includes("#{") && !hasPrivateUnicode,
  };

  for (const match of value.matchAll(/var\(\s*(--[\w-]+)/g)) {
    const definitions = variables.get(match[1]);

    if (!definitions) {
      result.complete = false;

      continue;
    }

    for (const definition of definitions) {
      const nestedValues = readCssValues(definition, variables, depth + 1);
      nestedValues.names.forEach((name) => result.names.add(name));
      result.complete &&= nestedValues.complete;
    }
  }

  return result;
}

function decodeCssString(value: string) {
  return value.replace(
    /\\([\da-f]{1,6})(?:\r\n|[\t\r\n\f ])?|\\([^\r\n\f])/gi,
    (_, hex: string | undefined, escaped: string) => {
      if (!hex) {
        return escaped;
      }

      const point = Number.parseInt(hex, 16);

      return point && point <= 0x10ffff ? String.fromCodePoint(point) : "�";
    }
  );
}
