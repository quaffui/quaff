import { writeFile } from "node:fs/promises";
import { QUAFF_COMPONENT_NAMES } from "../src/lib/autoImports.js";

const declarations = QUAFF_COMPONENT_NAMES.map(
  (name) => `  const ${name}: typeof import("./index.js")["${name}"];`
).join("\n");

await writeFile(
  new URL("../dist/auto-imports-globals.d.ts", import.meta.url),
  `// Generated by scripts/generateAutoImports.ts.\nexport {};\n\ndeclare global {\n${declarations}\n}\n`
);
